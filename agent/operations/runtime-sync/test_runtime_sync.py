    def test_descriptions_in_other_yaml_shapes(self):
        agents = self.brain / "agent" / "agents"
        (agents / "plain.md").write_text("---\nname: plain\ndescription: Use when the first line\n  continues here # a comment\n---\nBody.\n")
        (agents / "quoted.md").write_text('---\nname: quoted\ndescription: "Use when quoted\n  across lines"\n---\nBody.\n')
        (agents / "control.md").write_text('---\nname: control\ndescription: "Has a DEL \\u007f here"\n---\nBody.\n')
        (agents / "empty.md").write_text("---\nname: empty\ndescription: No prompt\n---\n\n")
        (agents / "trailing.md").write_text('---\nname: trailing\ndescription: "Use when y" # c\n---\nBody.\n')
        (agents / "spaced.md").write_text("---\nname: spaced\ndescription:\n  Use when x\n  and y\n---\nBody.\n")
        code, out = self.sync()
        self.assertEqual(code, 1)
        self.assertIn("empty.md has no prompt", out)
        codex = self.home / ".codex" / "agents"
        self.assertFalse((codex / "empty.toml").exists())
        if tomllib:
            read = lambda name: tomllib.loads((codex / f"{name}.toml").read_text())["description"]
            self.assertEqual(read("plain"), "Use when the first line continues here")
            self.assertEqual(read("quoted"), "Use when quoted across lines")
            self.assertEqual(read("control"), "Has a DEL \x7f here")
            self.assertEqual(read("trailing"), "Use when y")
            self.assertEqual(read("spaced"), "Use when x and y")

