"""Tests for runtime_sync.py against throwaway brains and home folders.

Usage: python3 test_runtime_sync.py   (touches nothing outside a temporary directory)
"""

import contextlib
import io
import os
import tempfile
import unittest
from pathlib import Path

import runtime_sync

try:
    import tomllib
except ImportError:  # Python before 3.11
    tomllib = None

VERIFIER = '''---
name: verifier
disallowedTools: mcp__monet
description: "Use when proof matters: it returns a verdict \\"with evidence\\"."
model: opus
source: https://example.com/verifier.md
---
Verifier

Checks claims. A path like C:\\temp and three quotes """ survive.
'''

FOLDED = '''---
name: scout
description: >
  Use when the ground is unknown;
  returns a map.
---
Scout body.
'''


class RuntimeSyncTest(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        root = Path(self.tmp.name)
        self.brain, self.home = root / "brain", root / "home"
        (self.brain / "agent" / "agents").mkdir(parents=True)
        (self.brain / "BRAIN.md").write_text("# BRAIN\n")
        (self.brain / "agent" / "agents" / "README.md").write_text("# Agents\n\nNo frontmatter here.\n")
        (self.brain / "agent" / "agents" / "verifier.md").write_text(VERIFIER)
        (self.brain / "agent" / "agents" / "scout.md").write_text(FOLDED)
        for skill in ("alpha", "beta", "group/nested"):
            (self.brain / "agent" / "skills" / skill).mkdir(parents=True)
            (self.brain / "agent" / "skills" / skill / "SKILL.md").write_text(f"---\nname: {skill}\n---\n")
        pointer = f"Read {self.brain}/BRAIN.md first.\n"
        (self.home / ".claude" / "skills" / "synced" / "acct").mkdir(parents=True)
        (self.home / ".claude" / "CLAUDE.md").write_text(pointer)
        self.outside = root / "elsewhere" / "vendor-skill"
        self.outside.mkdir(parents=True)
        (self.home / ".claude" / "skills" / "vendor").symlink_to(self.outside)
        (self.home / ".codex" / "agents").mkdir(parents=True)
        (self.home / ".codex" / "AGENTS.md").write_text(pointer)
        (self.home / ".codex" / "agents" / "verifier.toml").write_text('name = "verifier"\n# hand-made copy\n')
        (self.home / ".codex" / "agents" / "keeper.toml").write_text('name = "keeper"\n')
        (self.home / ".config" / "opencode").mkdir(parents=True)
        (self.home / ".config" / "opencode" / "AGENTS.md").write_text(pointer)

    def tearDown(self):
        self.tmp.cleanup()

    def sync(self, *extra):
        out = io.StringIO()
        with contextlib.redirect_stdout(out):
            code = runtime_sync.main(["--brain", str(self.brain), "--home", str(self.home), *extra])
        return code, out.getvalue()

    def test_first_run_links_and_generates(self):
        code, out = self.sync()
        self.assertEqual(code, 0, out)
        skills = self.home / ".claude" / "skills"
        self.assertFalse(skills.is_symlink())
        self.assertEqual(os.path.realpath(skills / "alpha"), os.path.realpath(self.brain / "agent" / "skills" / "alpha"))
        self.assertTrue((skills / "beta").is_symlink())
        self.assertFalse((skills / "nested").exists(), "only top-level skills are linked")
        self.assertTrue((skills / "synced" / "acct").is_dir(), "Claude Code's own folder is left alone")
        self.assertTrue((skills / "vendor").is_symlink(), "a link outside the brain is left alone")
        self.assertEqual(os.path.realpath(self.home / ".claude" / "agents"), os.path.realpath(self.brain / "agent" / "agents"))
        self.assertEqual(os.path.realpath(self.home / ".agents" / "skills"), os.path.realpath(self.brain / "agent" / "skills"))

        codex = self.home / ".codex" / "agents"
        self.assertEqual(sorted(p.name for p in codex.glob("*.toml")), ["keeper.toml", "scout.toml", "verifier.toml"])
        backups = list(codex.glob("verifier.toml.bak-o2b-*"))
        self.assertEqual(len(backups), 1, "the hand-made copy is moved aside, not lost")
        self.assertIn("hand-made copy", backups[0].read_text())
        self.assertEqual((codex / "keeper.toml").read_text(), 'name = "keeper"\n', "an unrelated agent is untouched")
        text = (codex / "verifier.toml").read_text()
        self.assertTrue(text.startswith("# Generated by O2B from "))
        if tomllib:
            data = tomllib.loads(text)
            self.assertEqual(data["name"], "verifier")
            self.assertEqual(data["description"], 'Use when proof matters: it returns a verdict "with evidence".')
            self.assertIn('C:\\temp and three quotes """ survive.', data["developer_instructions"])
            self.assertNotIn("model", data)
            self.assertEqual(tomllib.loads((codex / "scout.toml").read_text())["description"], "Use when the ground is unknown; returns a map.")

        opencode = self.home / ".config" / "opencode" / "agents"
        self.assertEqual(sorted(p.name for p in opencode.iterdir()), ["scout.md", "verifier.md"], "README.md is not an agent")
        oc = (opencode / "verifier.md").read_text()
        self.assertIn("\nmode: subagent\n", oc)
        self.assertNotIn("model:", oc)
        self.assertTrue(oc.split("---\n", 2)[2].startswith("Verifier\n"))

    def test_second_run_is_silent(self):
        self.sync()
        code, out = self.sync()
        self.assertEqual((code, out), (0, ""))

    def test_whole_folder_link_becomes_per_skill_links(self):
        skills = self.home / ".claude" / "skills"
        for entry in skills.iterdir():
            entry.unlink() if entry.is_symlink() else None
        os.rename(skills, self.home / "old-skills")
        skills.symlink_to(self.brain / "agent" / "skills")
        code, out = self.sync()
        self.assertEqual(code, 0, out)
        self.assertFalse(skills.is_symlink())
        self.assertTrue((skills / "alpha").is_symlink())
        self.assertEqual(sorted(p.name for p in (self.brain / "agent" / "skills").iterdir()), ["alpha", "beta", "group"], "the brain's own folder is untouched")

    def test_removed_sources_are_cleaned_up(self):
        self.sync()
        (self.brain / "agent" / "agents" / "scout.md").unlink()
        (self.brain / "agent" / "skills" / "beta" / "SKILL.md").unlink()
        (self.brain / "agent" / "skills" / "beta").rmdir()
        code, out = self.sync()
        self.assertEqual(code, 0, out)
        self.assertFalse((self.home / ".codex" / "agents" / "scout.toml").exists())
        self.assertFalse((self.home / ".config" / "opencode" / "agents" / "scout.md").exists())
        self.assertFalse((self.home / ".claude" / "skills" / "beta").is_symlink())
        self.assertTrue((self.home / ".codex" / "agents" / "keeper.toml").exists())

    def test_other_brains_files_are_not_removed(self):
        (self.home / ".codex" / "agents" / "other.toml").write_text("# " + runtime_sync.MARK.format(source="/another/brain/agent/agents/other.md") + "\n")
        self.sync()
        self.assertTrue((self.home / ".codex" / "agents" / "other.toml").exists())

    def test_real_folder_is_reported_not_replaced(self):
        (self.home / ".claude" / "agents").mkdir()
        (self.home / ".claude" / "agents" / "mine.md").write_text("---\ndescription: mine\n---\n")
        code, out = self.sync()
        self.assertEqual(code, 1)
        self.assertIn(".claude/agents is a real folder", out)
        self.assertTrue((self.home / ".claude" / "agents" / "mine.md").exists())

    def test_missing_pointer_is_reported_once_with_state(self):
        (self.home / ".codex" / "AGENTS.md").write_text("")
        state = Path(self.tmp.name) / "state"
        code, out = self.sync("--state", str(state))
        self.assertEqual(code, 1)
        self.assertIn("Codex:", out)
        code, out = self.sync("--state", str(state))
        self.assertEqual((code, out), (0, ""))
        (self.home / ".codex" / "AGENTS.md").write_text(f"Read {self.brain}/BRAIN.md\n")
        code, out = self.sync("--state", str(state))
        self.assertEqual(code, 0)
        self.assertIn("resolved", out)
        self.assertFalse(state.exists())

    def test_dry_run_changes_nothing(self):
        before = sorted(str(p) for p in self.home.rglob("*"))
        code, out = self.sync("--dry-run")
        self.assertEqual(code, 0, out)
        self.assertIn("dry run: wrote", out)
        self.assertEqual(sorted(str(p) for p in self.home.rglob("*")), before)

    def test_only_installed_runtimes_are_touched(self):
        for name in (".codex", ".config"):
            for path in sorted((self.home / name).rglob("*"), reverse=True):
                path.unlink() if path.is_file() or path.is_symlink() else path.rmdir()
            (self.home / name).rmdir()
        self.sync()
        self.assertFalse((self.home / ".codex").exists())
        self.assertFalse((self.home / ".agents").exists())

    def test_filesystem_error_is_reported_once_not_raised(self):
        (self.home / ".agents").symlink_to(Path(self.tmp.name) / "missing")
        state = Path(self.tmp.name) / "state"
        code, out = self.sync("--state", str(state))
        self.assertEqual(code, 1)
        self.assertIn("folder_link failed", out)
        self.assertTrue((self.home / ".codex" / "agents" / "verifier.toml").exists(), "later runtimes still ran")
        self.assertEqual(self.sync("--state", str(state)), (0, ""))

    def test_runtime_folder_inside_the_brain_is_refused(self):
        opencode = self.home / ".config" / "opencode"
        for path in opencode.iterdir():
            path.unlink()
        opencode.rmdir()
        opencode.symlink_to(self.brain / "agent")
        before = (self.brain / "agent" / "agents" / "verifier.md").read_text()
        code, out = self.sync()
        self.assertEqual(code, 1)
        self.assertIn("outside the brain", out)
        self.assertEqual((self.brain / "agent" / "agents" / "verifier.md").read_text(), before)
        self.assertEqual(list((self.brain / "agent" / "agents").glob("*.bak-o2b-*")), [])

    def test_dangling_link_outside_the_brain_is_left_alone(self):
        link = self.home / ".claude" / "skills" / "alpha"
        link.symlink_to("/Volumes/NotMounted/alpha")
        code, out = self.sync()
        self.assertEqual(code, 1)
        self.assertEqual(os.readlink(link), "/Volumes/NotMounted/alpha")

    def test_other_spellings_of_the_brain_are_the_same_brain(self):
        alias = Path(self.tmp.name) / "brain-alias"
        alias.symlink_to(self.brain)
        self.assertEqual(self.sync()[0], 0)
        code, out = runtime_sync.main(["--brain", str(alias), "--home", str(self.home)]), None
        self.assertEqual(code, 0)
        self.assertEqual(len(list((self.home / ".codex" / "agents").glob("*.bak-o2b-*"))), 1, "only the hand-made copy")
        cwd = os.getcwd()
        try:
            os.chdir(self.tmp.name)
            out = io.StringIO()
            with contextlib.redirect_stdout(out):
                self.assertEqual(runtime_sync.main(["--brain", "brain", "--home", str(self.home)]), 0)
            self.assertEqual(out.getvalue(), "", "a relative --brain changes nothing")
        finally:
            os.chdir(cwd)

    def test_pointer_may_name_the_brain_any_way(self):
        alias = Path(self.tmp.name) / "brain-alias"
        alias.symlink_to(self.brain)
        (self.home / ".claude" / "CLAUDE.md").write_text(f"Read `{alias}/BRAIN.md` first.\n")
