#!/usr/bin/env python3
"""Keep each agent runtime on this machine in step with the brain's skills and agent definitions.

See ../skill-discovery.md. ../sync/sync.sh runs it at the end of each sync; run it by hand after
setting up a machine:

    python3 runtime_sync.py [--dry-run]

Python 3.9 standard library only, so macOS's /usr/bin/python3 can run it.
"""

import argparse
import datetime
import json
import os
import re
import sys
from pathlib import Path

MARK = "Generated by O2B from {source}; edit the source, not this file."
MARK_PREFIX = "Generated by O2B from "
KEY = re.compile(r"^([A-Za-z0-9_-]+):(?:[ \t]+(.*))?$")
BLOCK = re.compile(r"[>|](?:[1-9][+-]?|[+-][1-9]?)?(?:\s+#.*)?")
ESCAPES = r'\\(?:[0abt\tnvfre "/\\N_LP]|x[0-9A-Fa-f]{2}|u[0-9A-Fa-f]{4}|U[0-9A-Fa-f]{8})'
REQUOTED = re.compile(r"[{}\[\]*&#!|>%@`]|: ")
NOT_TEXT = re.compile(r"~|null|Null|NULL|true|True|TRUE|false|False|FALSE|[-+]?(?:\d+(?:\.\d*)?|\.\d+)(?:[eE][-+]?\d+)?|0x[0-9a-fA-F]+|0o[0-7]+|[-+]?\.(?:inf|Inf|INF)|\.(?:nan|NaN|NAN)")
NAME = re.compile(r"[a-z0-9]+(?:-[a-z0-9]+)*")


def unquote(value):
    value = value.strip()
    double = re.fullmatch(r'"((?:[^"\\]|\\.)*)"(?:\s+#.*)?', value, re.S)
    if double:
        try:
            return json.loads('"' + double.group(1) + '"')
        except ValueError:
            return double.group(1)
    single = re.fullmatch(r"'((?:[^']|'')*)'(?:\s+#.*)?", value, re.S)
    if single:
        return single.group(1).replace("''", "'")
    return re.sub(r"\s+#.*$", "", value)


def closed(value):
    """Whether a value that opens a quote also closes it on this line."""
    quote = value[:1]
    if quote not in ('"', "'"):
        return True
    if quote == "'":
        return len(value) >= 2 and value.replace("''", "").endswith("'")
    return len(value) >= 2 and re.search(r'(?<!\\)(\\\\)*"$', value[1:]) is not None


def flow_closed(value):
    """Whether a value is one complete `[ ]` or `{ }` collection, ignoring quoted text."""
    depth, quote, i = 0, None, 0
    while i < len(value):
        c = value[i]
        if quote:
            if quote == '"' and c == "\\":
                i += 2
                continue
            if c == quote:
                if quote == "'" and value[i + 1:i + 2] == "'":
                    i += 2
                    continue
                quote = None
        elif c in "\"'":
            quote = c
        elif c in "[{":
            depth += 1
        elif c in "]}":
            depth -= 1
            if depth == 0:
                rest = value[i + 1:].strip()
                return not rest or rest.startswith("#")
        i += 1
    return False


def quote_problem(value):
    """Why a quoted value on its key's line cannot be read, or None (also None for unquoted values)."""
    if value[:1] == '"':
        ok = re.fullmatch(r'"((?:[^"\\]|' + ESCAPES + r')*)"(?:\s+#.*)?', value, re.S)
        return None if ok else "has a quoted value that is not closed, has an invalid escape, or has text after its closing quote"
    if value[:1] == "'":
        ok = re.fullmatch(r"'((?:[^']|'')*)'(?:\s+#.*)?", value, re.S)
        return None if ok else "has a quoted value that is not closed, or has text after its closing quote"
    return None


def parse_definition(path):
    """Read an agent definition: (frontmatter, body, problem), or None when it has no frontmatter.

    Reads frontmatter the way Claude Code loads an agent: values Claude Code would re-quote
    and accept, such as an unclosed `[`, a `: ` inside a value or an anchor, are read as text.
    `problem` names the first line Claude Code would refuse (an unclosed quote, a line that is
    not `key: value`, an indented line that belongs to no key) or a `name` or `description`
    that is not text; it is None when the definition can be generated. Measured against Claude
    Code 2.1.228's own reader on about 2,000 published definitions, the two agree except where a
    file has no line that is exactly `---`. Rarer shapes still differ: Claude Code also refuses a
    `: ` on a continued line, a re-quotable value in a file with Windows line endings, and bad
    content under an empty key other than `name` and `description`, which this reads.
    """
    try:
        text = path.read_bytes().decode("utf-8", errors="replace").lstrip("\ufeff")
    except OSError:
        return None
    lines = text.split("\n")
    if lines[0].rstrip() != "---":
        return None
    end = next((i for i in range(1, len(lines)) if lines[i].rstrip() == "---"), None)
    if end is None:
        return None
    body = "\n".join(lines[end + 1:])

    def continues(j):
        """Whether line j continues the value above: indented, or blank before an indented line."""
        if lines[j].strip():
            return lines[j][:1] in (" ", "\t")
        k = j
        while k < end and not lines[k].strip():
            k += 1
        return k < end and lines[k][:1] in (" ", "\t")

    meta = {}
    i = 1
    while i < end:
        line, number = lines[i], i + 1
        i += 1
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        if line[:1] in (" ", "\t"):
            return meta, body, f"line {number} is indented but belongs to no key"
        match = KEY.match(line)
        if not match:
            return meta, body, f"line {number} is not a `key: value` line"
        key, value = match.group(1), (match.group(2) or "").strip()
        if value.startswith("#"):
            value = ""
        if BLOCK.fullmatch(value):
            block = []
            while i < end and (lines[i][:1] in (" ", "\t") or not lines[i].strip()):
                block.append(lines[i].strip())
                i += 1
            if value.startswith(">"):
                value = " ".join(line for line in block if line)
            else:
                value = "\n".join(block).strip("\n")
        else:
            inline, nested = value, []
            while i < end and continues(i) and (not closed(value) or value[:1] not in ('"', "'")):
                if lines[i].strip():
                    value += " " + lines[i].strip()
                    nested.append(lines[i].strip())
                i += 1
            if not inline:
                while i < end and lines[i].startswith("- "):
                    value += " " + lines[i].strip()
                    nested.append(lines[i].strip())
                    i += 1
            problem = quote_problem(value)
            if problem and not nested and inline[:1] != inline[-1:] and REQUOTED.search(inline):
                # Claude Code re-quotes a key line whose value opens a quote without closing it
                # and holds a `: ` or another YAML indicator, so it reads the line as plain text.
                meta[key] = inline
                continue
            if problem:
                return meta, body, f"line {number} {problem}"
            if key in ("name", "description"):
                if not inline and nested and (nested[0].startswith("- ") or (
                    nested[0][:1] not in ('"', "'") and re.search(r":(\s|$)", nested[0])
                )):
                    return meta, body, f"line {number} gives `{key}` a list or mapping, not text"
                scalar = inline or " ".join(nested)
                if scalar and scalar[0] in "[{" and flow_closed(scalar):
                    return meta, body, f"line {number} gives `{key}` a list or mapping, not text"
                if scalar and NOT_TEXT.fullmatch(re.sub(r"\s+#.*$", "", scalar)):
                    return meta, body, f"line {number} gives `{key}` a number, boolean or null, not text"
            value = unquote(value)
        meta[key] = value
    if not meta.get("description"):
        return meta, body, "has no `description:`"
    return meta, body, None


def clean_body(body):
    body = body.lstrip("\n")
    return body if body.endswith("\n") else body + "\n"


def quoted(text):
    # JSON string escapes are valid TOML basic-string and YAML double-quoted escapes; DEL is the
    # one control character JSON leaves raw, and TOML rejects it.
    return json.dumps(text, ensure_ascii=False).replace("\x7f", "\\u007f")


def toml_multiline(text):
    text = text.replace("\\", "\\\\").replace('"""', '""\\"')
    text = re.sub(r"[\x00-\x08\x0b-\x1f\x7f]", lambda m: "\\u%04x" % ord(m.group()), text)
    return '"""\n' + text + '"""'


def render_codex(source, meta, body):
    return "\n".join([
        "# " + MARK.format(source=source),
        "name = " + quoted(source.stem),
        "description = " + quoted(meta["description"]),
        "developer_instructions = " + toml_multiline(clean_body(body)),
    ]) + "\n"


def render_opencode(source, meta, body):
    return (
        "---\n"
        "# " + MARK.format(source=source) + "\n"
        "description: " + quoted(meta["description"]) + "\n"
        "mode: subagent\n"
        "---\n" + clean_body(body)
    )


def generated_source(path):
    """The source path named in a generated file's marker, or None."""
    try:
        with path.open(encoding="utf-8") as f:
            head = [f.readline() for _ in range(3)]
    except (OSError, UnicodeDecodeError):
        return None
    for line in head:
        start = line.find(MARK_PREFIX)
        end = line.find("; edit the source")
        if start != -1 and end > start:
            return line[start + len(MARK_PREFIX):end]
    return None


def link_target(link):
    target = os.readlink(link)
    return target if os.path.isabs(target) else os.path.join(os.path.dirname(link), target)


def same_path(a, b):
    return os.path.realpath(a) == os.path.realpath(b)


def inside(path, root):
    path, root = os.path.realpath(path), os.path.realpath(root)
    return path == root or path.startswith(root + os.sep)


class Sync:
    def __init__(self, brain, home, dry_run):
        self.brain = brain
        self.home = home
        self.dry = dry_run
        self.skills = brain / "agent" / "skills"
        self.agents = brain / "agent" / "agents"
        self.changes = []
        self.problems = []
        self.unusable = set()
        self.today = datetime.date.today().isoformat()

    def change(self, message):
        self.changes.append(("dry run: " if self.dry else "") + message)

    def problem(self, message):
        self.problems.append(message)

    def replaceable(self, link):
        """A link the brain may re-point: one pointing into this brain, even if its target is gone."""
        return inside(link_target(link), self.brain)

    def link(self, link, target):
        if not self.dry:
            if link.is_symlink():
                link.unlink()
            link.parent.mkdir(parents=True, exist_ok=True)
            link.symlink_to(target)

    def folder_link(self, link, target):
        """Make `link` a link to the whole brain folder `target`."""
        if not target.is_dir():
            return
        if inside(link.parent, self.brain):
            self.problem(f"{link.parent} is inside the brain; {link} was not linked")
            return
        if link.is_symlink():
            if same_path(link, target):
                return
            if self.replaceable(link):
                self.link(link, target)
                self.change(f"re-pointed {link} to {target}")
            else:
                self.problem(f"{link} links to {link_target(link)}, not {target}; change it by hand if the brain should own it")
        elif link.exists():
            self.problem(f"{link} is a real folder; move what it holds into {target}, remove it, and rerun")
        else:
            self.link(link, target)
            self.change(f"linked {link} to {target}")

    def skill_links(self, folder):
        """Keep one link per brain skill in a runtime's skills folder, leaving everything else alone."""
        if inside(folder.parent, self.brain):
            self.problem(f"{folder.parent} is inside the brain; skills were not linked there")
            return
        wanted = {}
        if self.skills.is_dir():
            wanted = {d.name: d for d in sorted(self.skills.iterdir()) if d.is_dir() and (d / "SKILL.md").is_file()}
        if folder.is_symlink():
            if not self.replaceable(folder):
                self.problem(f"{folder} links to {link_target(folder)}; change it by hand if the brain should own it")
                return
            if not self.dry:
                folder.unlink()
                folder.mkdir()
            self.change(f"replaced the link {folder} with a folder of per-skill links")
            if self.dry:
                self.change(f"linked {len(wanted)} skills into {folder}")
                return
        elif not folder.exists():
            if not self.dry:
                folder.mkdir(parents=True)
            self.change(f"created {folder}")
        elif not folder.is_dir():
            self.problem(f"{folder} is not a folder")
            return
        elif inside(folder, self.brain):
            self.problem(f"{folder} is inside the brain; skills were not linked there")
            return
        for name, skill in wanted.items():
            link = folder / name
            if link.is_symlink():
                if same_path(link, skill):
                    continue
                if self.replaceable(link):
                    self.link(link, skill)
                    self.change(f"re-pointed {link} to {skill}")
                else:
                    self.problem(f"{link} links to {link_target(link)}, not the brain's {name} skill")
            elif link.exists():
                self.problem(f"{link} is a real folder named like the brain's {name} skill; move it into the brain or rename it")
            else:
                self.link(link, skill)
                self.change(f"linked {link} to {skill}")
        if folder.is_dir():
            for entry in sorted(folder.iterdir()):
                if entry.is_symlink() and entry.name not in wanted:
                    target = link_target(entry)
                    if not os.path.exists(target) and inside(target, self.skills):
                        if not self.dry:
                            entry.unlink()
                        self.change(f"removed {entry}: the brain no longer has that skill")

    def definitions(self):
        found = {}
        if self.agents.is_dir():
            for path in sorted(self.agents.glob("*.md")):
                parsed = parse_definition(path)
                if not parsed:
                    if path.name != "README.md":
                        self.unusable.add(str(path))
                        self.problem(f"{path} cannot be read as an agent definition: it has no frontmatter between --- lines; it was not generated for other runtimes")
                    continue
                if parsed[2]:
                    self.unusable.add(str(path))
                    self.problem(f"{path} cannot be read as an agent definition: its frontmatter {parsed[2]}; it was not generated for other runtimes")
                    continue
                if parsed[0].get("name") != path.stem or not NAME.fullmatch(path.stem):
                    self.unusable.add(str(path))
                    self.problem(f"{path} needs a name of lowercase letters, digits and hyphens, matching its file name, as `name:` in its frontmatter; it was not generated for other runtimes")
                    continue
                if not parsed[1].strip():
                    self.unusable.add(str(path))
                    self.problem(f"{path} has no prompt after its frontmatter; it was not generated for other runtimes")
                    continue
                found[path.stem] = (path, parsed[0], parsed[1])
        return found

    def backup_name(self, path):
        base = f"{path.name}.bak-o2b-{self.today}"
        candidate, n = path.with_name(base), 2
        while candidate.exists() or candidate.is_symlink():
            candidate, n = path.with_name(f"{base}-{n}"), n + 1
        return candidate

    def generated(self, folder, suffix, render, definitions):
        """Write each definition in a runtime's own format; remove what this brain generated and no longer has."""
        if folder.is_symlink() or (folder.exists() and not folder.is_dir()) or inside(folder, self.brain):
            self.problem(f"{folder} is not a plain folder outside the brain; agent definitions were not generated there")
            return
        if not folder.exists():
            if not self.dry:
                folder.mkdir(parents=True)
            self.change(f"created {folder}")
        for name, (source, meta, body) in definitions.items():
            path = folder / f"{name}{suffix}"
            content = render(source, meta, body)
            current = None
            marked = generated_source(path) if path.exists() and not path.is_symlink() else None
            if path.is_symlink() or (path.exists() and not (marked and same_path(marked, source))):
                backup = self.backup_name(path)
                if not self.dry:
                    path.rename(backup)
                self.change(f"moved {path} aside to {backup.name}: it was not generated from {source}")
            elif path.exists():
                current = path.read_text(encoding="utf-8")
            if current != content:
                if not self.dry:
                    path.write_text(content, encoding="utf-8")
                self.change(("updated " if current is not None else "wrote ") + str(path))
        if folder.is_dir():
            for path in sorted(folder.glob(f"*{suffix}")):
                if path.stem in definitions or path.is_symlink():
                    continue
                source = generated_source(path)
                if not source or not inside(source, self.agents):
                    continue
                if os.path.exists(source):
                    if source not in self.unusable:
                        self.unusable.add(source)
                        self.problem(f"{source} cannot be read as an agent definition; its generated copies were kept")
                    continue
                if not self.dry:
                    path.unlink()
                self.change(f"removed {path}: this brain no longer defines {path.stem}")

    def pointer(self, runtime, files):
        """Report a runtime whose global instructions do not send sessions to this brain's BRAIN.md."""
        entry = self.brain / "BRAIN.md"
        path = next((f for f in files if f.is_file()), files[-1])
        try:
            text = path.read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError):
            text = ""
        home = str(self.home)
        spellings = {str(entry), os.path.realpath(entry)}
        spellings |= {"~/" + os.path.relpath(os.path.realpath(s), os.path.realpath(home)) for s in list(spellings) if inside(s, home)}
        if any(s in text for s in spellings):
            return
        named = [n for n in re.findall(r"[^\s`'\"()<>\[\]]*BRAIN\.md", text) if n.startswith(("/", "~/"))]
        if not any(same_path(home + n[1:] if n.startswith("~/") else n, entry) for n in named):
            self.problem(f"{runtime}: {path} does not tell sessions to read {entry}")

    def gate_hook(self, settings):
        """Report a Claude Code whose user settings do not run the brain's gate hook. See ../gate-hook.md."""
        script = self.brain / "agent" / "operations" / "gate-hook" / "gate_hook.py"
        if not script.is_file():
            return
        try:
            data = json.loads(settings.read_text(encoding="utf-8")) if settings.is_file() else {}
        except (OSError, ValueError) as error:
            self.problem(f"Claude Code: {settings} cannot be read ({error}), so its gate hook was not checked")
            return
        hooks = data.get("hooks") if isinstance(data, dict) else None
        groups = hooks.get("PreToolUse") if isinstance(hooks, dict) else None
        spellings = {str(script), os.path.realpath(script)}
        home = os.path.realpath(self.home)
        spellings |= {prefix + os.path.relpath(s, home) for s in list(spellings) if inside(s, home) for prefix in ("~/", "$HOME/")}
        for group in groups if isinstance(groups, list) else []:
            for handler in group.get("hooks") or [] if isinstance(group, dict) else []:
                command = handler.get("command") if isinstance(handler, dict) else None
                if isinstance(command, str) and any(s in command for s in spellings):
                    return
        self.problem(f"Claude Code: {settings} does not run {script} before Bash commands; add it with `python3 {script} --install`")

    def step(self, action, *args):
        """Run one step; a filesystem or decoding error becomes a reported problem instead of ending the run."""
        try:
            action(*args)
        except (OSError, ValueError) as error:
            self.problem(f"{action.__name__} failed: {error}")

    def run(self):
        home = self.home
        definitions = self.definitions()
        claude = (home / ".claude").is_dir()
        codex = (home / ".codex").is_dir()
        opencode = (home / ".config" / "opencode").is_dir()
        if claude:
            self.step(self.skill_links, home / ".claude" / "skills")
            self.step(self.folder_link, home / ".claude" / "agents", self.agents)
            self.step(self.pointer, "Claude Code", [home / ".claude" / "CLAUDE.md"])
            self.step(self.gate_hook, home / ".claude" / "settings.json")
        if codex or opencode:
            self.step(self.folder_link, home / ".agents" / "skills", self.skills)
        if codex:
            self.step(self.generated, home / ".codex" / "agents", ".toml", render_codex, definitions)
            self.step(self.pointer, "Codex", [home / ".codex" / "AGENTS.override.md", home / ".codex" / "AGENTS.md"])
        if opencode:
            self.step(self.generated, home / ".config" / "opencode" / "agents", ".md", render_opencode, definitions)
            self.step(self.pointer, "opencode", [home / ".config" / "opencode" / "AGENTS.md", home / ".claude" / "CLAUDE.md"])
        if (home / ".hermes").is_dir():
            self.step(self.pointer, "Hermes", [home / ".hermes" / "SOUL.md"])
        return self


def main(argv=None):
    parser = argparse.ArgumentParser(description="Keep agent runtimes in step with the brain's skills and agent definitions.")
    parser.add_argument("--brain", help="the live brain (default: the one holding this script)")
    parser.add_argument("--home", default=str(Path.home()), help="the home folder whose runtimes to update")
    parser.add_argument("--dry-run", action="store_true", help="report what would change without changing it")
    parser.add_argument("--state", help="file that remembers reported problems, so repeated runs report only new ones")
    args = parser.parse_args(argv)
    brain = Path(args.brain).expanduser().resolve() if args.brain else Path(__file__).resolve().parents[3]
    home = Path(args.home).expanduser().absolute()
    if not (brain / "BRAIN.md").is_file():
        print(f"runtime-sync: {brain} has no BRAIN.md, so it is not a brain")
        return 2
    sync = Sync(brain, home, args.dry_run).run()
    for message in sync.changes:
        print("runtime-sync: " + message)
    report = "\n".join(sync.problems)
    if args.state and not args.dry_run:
        state = Path(args.state)
        previous = state.read_text(encoding="utf-8") if state.is_file() else ""
        if report == previous:
            return 0
        if report:
            state.write_text(report, encoding="utf-8")
        else:
            state.unlink()
            print("runtime-sync: the problems reported earlier are resolved")
            return 0
    for message in sync.problems:
        print("runtime-sync: attention: " + message)
    return 1 if sync.problems else 0


if __name__ == "__main__":
    sys.exit(main())
